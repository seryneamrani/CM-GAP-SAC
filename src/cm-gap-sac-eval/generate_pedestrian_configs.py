"""
Generate pedestrian_manager YAML configs — one per scenario in eval_config.yaml.

Uses YOUR pedestrian waypoints and behaviors from your existing training config,
scaled per scenario:
    - Scenario speed 0.3 m/s (low dynamicity) → fast peds at 0.3, slow peds at 0.15
    - Scenario speed 0.5 m/s (high dynamicity) → fast peds at 0.5, slow peds at 0.25
    - Number of pedestrians clipped to scenario's n_pedestrians (first N in template)

The "slow" pedestrians (50% ratio) are peds 2, 4, 7 — matching your training config.

Usage:
    python generate_pedestrian_configs.py \\
        --eval-config config/eval_config.yaml \\
        --output-dir configs/pedestrian_scenarios/
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml


# ==============================================================================
# Pedestrian templates — YOUR exact waypoints from training pedestrians.yaml
# ------------------------------------------------------------------------------
# Each entry: (name, waypoints, speed_ratio)
#   waypoints  = list of [x, y] pairs (2-point ping-pong)
#   speed_ratio = 1.0 for default-speed peds, 0.5 for slow peds (matches your
#                 explicit `speed: 0.25` overrides at global dynamicity=medium)
# ==============================================================================
PEDESTRIAN_TEMPLATES = [
    {"name": "ped_1", "waypoints": [[5.43, 1.62],  [2.40, 1.62]],  "speed_ratio": 1.0},
    {"name": "ped_2", "waypoints": [[-3.92, 1.18], [-6.92, 1.18]], "speed_ratio": 0.5},
    {"name": "ped_4", "waypoints": [[-6.75, -1.77],[-3.73, -1.77]],"speed_ratio": 0.5},
    {"name": "ped_5", "waypoints": [[2.75, -6.50], [2.75, -4.14]], "speed_ratio": 1.0},
    {"name": "ped_6", "waypoints": [[-1.65, -4.20],[-1.65, -6.50]],"speed_ratio": 1.0},
    {"name": "ped_7", "waypoints": [[2.75, 6.50],  [2.75, 4.20]],  "speed_ratio": 0.5},
    {"name": "ped_8", "waypoints": [[-1.76, 4.20], [-1.76, 6.50]], "speed_ratio": 1.0},
]


def build_scenario_config(scenario: dict, world_name: str = "hospital") -> dict:
    """Build a pedestrian_manager YAML dict for one scenario.

    scenario keys used:
        id, n_pedestrians, pedestrian_speed_mps
    """
    n_ped = int(scenario["n_pedestrians"])
    scenario_speed = float(scenario["pedestrian_speed_mps"])

    if n_ped > len(PEDESTRIAN_TEMPLATES):
        raise ValueError(
            f"Scenario {scenario['id']} requires {n_ped} peds but only "
            f"{len(PEDESTRIAN_TEMPLATES)} templates available"
        )

    pedestrians = []
    for template in PEDESTRIAN_TEMPLATES[:n_ped]:
        # scenario_speed is the "fast" ped speed. Slow peds get half.
        per_ped_speed = scenario_speed * template["speed_ratio"]
        pedestrians.append({
            "name": template["name"],
            "waypoints": template["waypoints"],
            "behavior": "ping_pong",
            "speed": round(per_ped_speed, 3),
            "pause_at_endpoints": 1.0,
        })

    return {
        "global": {
            "world_name": world_name,
            "update_rate_hz": 30.0,           # matches your training config
            "arrival_tolerance": 0.15,        # matches your training config
            "dynamicity": "medium",           # baseline profile (unused, per-ped speed overrides)
            "speed_scale": 1.0,
        },
        "pedestrians": pedestrians,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--eval-config", type=Path, required=True,
                    help="Path to eval_config.yaml (source of scenarios)")
    ap.add_argument("--output-dir", type=Path, default=Path("configs/pedestrian_scenarios"))
    ap.add_argument("--world", type=str, default="hospital")
    args = ap.parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)

    with args.eval_config.open() as f:
        eval_cfg = yaml.safe_load(f)

    print(f"Generating pedestrian configs for {len(eval_cfg['scenarios'])} scenarios")
    print(f"Output: {args.output_dir}/\n")

    for scenario in eval_cfg["scenarios"]:
        n = int(scenario["n_pedestrians"])
        speed = float(scenario["pedestrian_speed_mps"])

        # S1 static-only: no pedestrians, no config needed — but write empty
        # config anyway so the runbook can uniformly reference the file.
        if n == 0:
            ped_cfg = {
                "global": {
                    "world_name": args.world, "update_rate_hz": 30.0,
                    "arrival_tolerance": 0.15, "dynamicity": "medium",
                    "speed_scale": 1.0,
                },
                "pedestrians": [],
            }
        else:
            ped_cfg = build_scenario_config(scenario, world_name=args.world)

        out = args.output_dir / f"{scenario['id']}.yaml"
        header = (
            f"# Auto-generated by generate_pedestrian_configs.py — do not edit by hand.\n"
            f"# Scenario: {scenario['id']}\n"
            f"# {scenario.get('description', '')}\n"
            f"# n_pedestrians: {n}   fast_speed: {speed} m/s   "
            f"slow_speed: {speed * 0.5} m/s (peds 2, 4, 7)\n"
            f"# ---\n"
            f"# Loaded by:\n"
            f"#   ros2 run pedestrian_manager pedestrian_manager_node \\\n"
            f"#       --ros-args -p config_file:={out.resolve()}\n"
            f"# ---\n\n"
        )
        with out.open("w") as f:
            f.write(header)
            yaml.safe_dump(ped_cfg, f, default_flow_style=False, sort_keys=False)

        slow_note = " (peds 2/4/7 at half-speed)" if n >= 2 else ""
        print(f"  {scenario['id']:<25s}  n={n}  fast_speed={speed} m/s{slow_note}")

    print(f"\nDone. {len(eval_cfg['scenarios'])} configs written.")


if __name__ == "__main__":
    main()
